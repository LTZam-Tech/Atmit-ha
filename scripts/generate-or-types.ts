/**
 * Validates the Smart OR of every app and generates apps/<app>/or/or.types.gen.ts so that
 * page.el('usrname') (typo) or a missing {sku} parameter fails in the IDE, not at runtime.
 *
 *   npm run or:types       validate + generate (all apps)
 *   npm run validate       validate OR + no-code cases of every app, no files written (CI gate)
 */
import fs from 'node:fs';
import path from 'node:path';
import { listApps, orDir } from '../src/core/app';
import { readRepository, paramsOf } from '../src/core/or/loader';
import { readCases } from '../src/core/cases/loader';
import { readFlows } from '../src/core/cases/flows';
import { readNavigation } from '../src/core/navigation';

const checkOnly = process.argv.includes('--check');
let failed = false;

for (const app of listApps()) {
  try {
    const repo = readRepository(orDir(app));
    let elements = 0;
    const lines: string[] = [
      `// AUTO-GENERATED by \`npm run or:types\` from apps/${app}/or/*.page.yml — do not edit.`,
      '/* eslint-disable */',
      'export interface ORRegistry {',
    ];
    for (const [key, page] of repo) {
      lines.push(`  ${key}: {`);
      for (const name of Object.keys(page.elements)) {
        elements++;
        const params = paramsOf(page, name);
        const type = params.length ? `{ ${params.map((p) => `${p}: string | number`).join('; ')} }` : 'undefined';
        const desc = page.elements[name].description;
        if (desc) lines.push(`    /** ${desc} */`);
        lines.push(`    ${name}: ${type};`);
      }
      lines.push('  };');
    }
    lines.push('}', '', 'export type ORPageKey = keyof ORRegistry;', '');
    if (!checkOnly && fs.existsSync(orDir(app))) fs.writeFileSync(path.join(orDir(app), 'or.types.gen.ts'), lines.join('\n'));
    console.log(`✔ ${app}: Smart OR valid — ${repo.size} page(s), ${elements} element(s)`);
    const { cases, issues } = readCases(app);
    if (issues.length) {
      failed = true;
      for (const i of issues) console.error(`✖ ${app}: cases/${i.file} — ${i.message}`);
    } else if (cases.length) console.log(`✔ ${app}: ${cases.length} case file(s) valid`);
    const fl = readFlows(cases.filter((c) => !issues.some((i) => i.file === c.file)), app);
    if (fl.issues.length) { failed = true; for (const i of fl.issues) console.error(`✖ ${app}: flows/${i.file} — ${i.message}`); }
    else if (fl.flows.length) console.log(`✔ ${app}: ${fl.flows.length} workflow(s) valid`);
    const nav = readNavigation(app, repo);
    if (nav.issues.length) { failed = true; for (const i of nav.issues) console.error(`✖ ${app}: ${i}`); }
    else if (nav.edges.length) console.log(`✔ ${app}: navigation map — ${nav.edges.length} route(s)`);
    for (const p of repo.values()) {
      if (p.open === 'navigate' && !nav.edges.some((e) => e.to === p.page)) { failed = true; console.error(`✖ ${app}: page "${p.page}" opens through navigation but no route reaches it`); }
    }
  } catch (e) {
    failed = true;
    console.error(`✖ ${app}: ${(e as Error).message}`);
  }
}
if (failed) process.exit(1);

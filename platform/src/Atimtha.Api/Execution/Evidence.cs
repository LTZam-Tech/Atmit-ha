using System.Security.Cryptography;

namespace Atimtha.Api.Execution;

// Evidence of a test result: screenshots, videos, traces (ERD E20, backlog §11), mapped onto db/migrations/0001.

public enum EvidenceKind { Screenshot, Video, Trace, Log, Har, Other }

public sealed class Evidence
{
    public Guid Id { get; set; }
    public Guid OrganizationId { get; set; }
    public Guid TestResultId { get; set; }
    public EvidenceKind Kind { get; set; }
    public string Name { get; set; } = "";
    public string ObjectKey { get; set; } = "";
    public string ContentType { get; set; } = "";
    public long SizeBytes { get; set; }
    public string Sha256 { get; set; } = "";
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset? ExpiresAt { get; set; }
}

/// <summary>Where evidence bytes live. Object keys are generated by the platform, never taken from a request.</summary>
public interface IEvidenceStore
{
    Task PutAsync(string objectKey, byte[] content, CancellationToken ct);
    Task<byte[]?> GetAsync(string objectKey, CancellationToken ct);
    Task DeleteAsync(string objectKey, CancellationToken ct);
}

/// <summary>
/// Evidence on a local or mounted volume (Evidence:Directory), encrypted at rest with AES-256-GCM when
/// Evidence:EncryptionKey (base64, 32 bytes) is set. Layout of an encrypted object: "ATE1" | nonce(12) | tag(16) | ciphertext.
/// Screenshots of the application under test can show personal data, so production must set the key.
/// </summary>
public sealed class FileEvidenceStore : IEvidenceStore
{
    private static readonly byte[] Magic = "ATE1"u8.ToArray();
    private readonly string root;
    private readonly byte[]? key;

    public FileEvidenceStore(IConfiguration configuration, IHostEnvironment env, ILogger<FileEvidenceStore> logger)
    {
        root = Path.GetFullPath(configuration["Evidence:Directory"] ?? Path.Combine(env.ContentRootPath, "evidence"));
        var k = configuration["Evidence:EncryptionKey"];
        if (!string.IsNullOrWhiteSpace(k))
        {
            key = Convert.FromBase64String(k);
            if (key.Length != 32) throw new InvalidOperationException("Evidence:EncryptionKey must be 32 bytes, base64 encoded.");
        }
        else if (!env.IsDevelopment())
        {
            throw new InvalidOperationException("Set Evidence:EncryptionKey: evidence is encrypted at rest outside development.");
        }
        else
        {
            logger.LogWarning("Evidence is stored unencrypted (development only).");
        }
    }

    public async Task PutAsync(string objectKey, byte[] content, CancellationToken ct)
    {
        var path = PathOf(objectKey);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        var bytes = key is null ? content : Encrypt(content);
        var temp = path + ".part";
        await File.WriteAllBytesAsync(temp, bytes, ct);
        File.Move(temp, path, overwrite: true);
    }

    public async Task<byte[]?> GetAsync(string objectKey, CancellationToken ct)
    {
        var path = PathOf(objectKey);
        if (!File.Exists(path)) return null;
        var bytes = await File.ReadAllBytesAsync(path, ct);
        return bytes.AsSpan().StartsWith(Magic) ? Decrypt(bytes) : bytes;
    }

    public Task DeleteAsync(string objectKey, CancellationToken ct)
    {
        var path = PathOf(objectKey);
        if (File.Exists(path)) File.Delete(path);
        return Task.CompletedTask;
    }

    private string PathOf(string objectKey)
    {
        // keys look like <org>/<execution>/<evidence>: guids and slashes only
        if (objectKey.Length > 200 || objectKey.Any(c => !(char.IsAsciiHexDigit(c) || c is '-' or '/')) || objectKey.Contains("//"))
            throw new ArgumentException("Invalid evidence object key.", nameof(objectKey));
        var path = Path.GetFullPath(Path.Combine(root, objectKey));
        if (!path.StartsWith(root + Path.DirectorySeparatorChar, StringComparison.Ordinal)) throw new ArgumentException("Invalid evidence object key.", nameof(objectKey));
        return path;
    }

    private byte[] Encrypt(byte[] plain)
    {
        var output = new byte[Magic.Length + 12 + 16 + plain.Length];
        Magic.CopyTo(output, 0);
        var nonce = output.AsSpan(4, 12);
        RandomNumberGenerator.Fill(nonce);
        using var gcm = new AesGcm(key!, 16);
        gcm.Encrypt(nonce, plain, output.AsSpan(32), output.AsSpan(16, 16));
        return output;
    }

    private byte[] Decrypt(byte[] data)
    {
        if (key is null) throw new InvalidOperationException("Evidence is encrypted but Evidence:EncryptionKey is not set.");
        if (data.Length < 32) throw new CryptographicException("Truncated evidence object.");
        var plain = new byte[data.Length - 32];
        using var gcm = new AesGcm(key, 16);
        gcm.Decrypt(data.AsSpan(4, 12), data.AsSpan(32), data.AsSpan(16, 16), plain);
        return plain;
    }
}
